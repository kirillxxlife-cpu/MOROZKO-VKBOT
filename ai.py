async def get_ai_response(user_message: str, chat_history: list, client_name: str, current_step: str) -> str:
    step_context = ""
    if current_step == "address":
        step_context = "\n\nВАЖНО: Клиент сейчас на шаге ввода адреса. Ответь на его вопрос и вежливо попроси написать адрес."
    elif current_step == "phone":
        step_context = "\n\nВАЖНО: Клиент сейчас на шаге ввода телефона. Ответь на его вопрос и попроси написать номер."
    elif current_step == "child_name":
        step_context = "\n\nВАЖНО: Клиент вводит данные о ребенке. Ответь и попроси написать имя и возраст."

    system_prompt = BASE_SYSTEM_PROMPT + f"\n\nИмя клиента: {client_name}.{step_context}"
    
    messages = [{"role": "system", "content": system_prompt}]
    for msg in chat_history:
        messages.append({"role": msg["role"], "content": msg.get("text") or msg.get("content")})
    messages.append({"role": "user", "content": user_message})

    url = "https://llm.api.cloud.yandex.net/v1/chat/completions"
    headers = {"Authorization": f"Api-Key {YANDEX_API_KEY}", "Content-Type": "application/json"}
    payload = {
        "model": f"gpt://{YANDEX_FOLDER_ID}/aliceai-llm-flash/latest",
        "messages": messages,
        "temperature": 0.3,
        "max_tokens": 1000
    }

    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(url, headers=headers, json=payload, timeout=40) as resp:
                if resp.status == 200:
                    data = await resp.json()
                    return data["choices"][0]["message"]["content"].strip()
                else:
                    error_text = await resp.text()
                    logger.error(f"Yandex API Error {resp.status}: {error_text}")
                    return "Извините, произошла техническая ошибка. Попробуйте позже."
    except Exception as e:
        logger.error(f"Network error: {e}")
        return "Извините, произошла техническая ошибка. Попробуйте позже."
